/*
 * Read the flat dot map and write out what the hero needs to draw it.
 *
 * public/world-dots.svg is 1363 circles on a 1000x500 equirectangular grid.
 * That grid is longitude and latitude in disguise — x spans -180..180, y spans
 * 90..-90 — which is the only reason the three capitals can be placed on it
 * exactly rather than eyeballed.
 *
 * The dots come through unchanged: the map stays flat. What this adds is the
 * one thing the flat SVG could not carry — where Copenhagen, Oslo and
 * Stockholm are, in the same coordinate space as the land.
 */
import { readFileSync, writeFileSync } from "node:fs";

const W = 1000;
const H = 500;

const svg = readFileSync("public/world-dots.svg", "utf8");
const dots = [...svg.matchAll(/<circle cx="([\d.]+)" cy="([\d.]+)"/g)].map((m) => [
  +(+m[1]).toFixed(1),
  +(+m[2]).toFixed(1),
]);

/** Longitude/latitude to the map's own pixels. */
const at = (lon, lat) => [
  +(((lon + 180) / 360) * W).toFixed(1),
  +(((90 - lat) / 180) * H).toFixed(1),
];

const cities = {
  dk: at(12.57, 55.68), // København
  no: at(10.75, 59.91), // Oslo
  se: at(18.07, 59.33), // Stockholm
};

writeFileSync(
  "lib/globe-data.ts",
  `/* Generated by scripts/build/globe.mjs from public/world-dots.svg. Do not edit. */\n` +
    `export const MAP = { w: ${W}, h: ${H} } as const;\n` +
    `export const LAND: [number, number][] = ${JSON.stringify(dots)};\n` +
    `export const CITY = ${JSON.stringify(cities)} as const;\n`,
);
console.log(`dots: ${dots.length}`);
for (const [k, v] of Object.entries(cities)) console.log(k, v.join(", "));
