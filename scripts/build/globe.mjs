/*
 * Turn the flat dot map into a globe.
 *
 * public/world-dots.svg is 1363 circles on a 1000x500 equirectangular grid,
 * which is a lossless carrier for longitude and latitude: x maps to -180..180,
 * y maps to 90..-90. So the land is already measured — it only needs putting
 * on a sphere.
 *
 * Orthographic projection, the one that looks like a photograph of a planet
 * rather than a map of one: the far hemisphere is dropped, and what is left
 * carries a depth term that the renderer uses to shrink and dim dots toward
 * the limb. That falloff is the whole illusion.
 */
import { readFileSync, writeFileSync } from "node:fs";

const RAD = Math.PI / 180;
/* Centred where the business is: the Nordics sit high and centre-right, with
   enough of Europe and the Atlantic around them to read as Earth. */
const LON0 = 46 * RAD;
const LAT0 = 30 * RAD;

const svg = readFileSync("public/world-dots.svg", "utf8");
const dots = [...svg.matchAll(/<circle cx="([\d.]+)" cy="([\d.]+)"/g)].map((m) => [
  +m[1], +m[2],
]);

/** Orthographic: returns [x, y, depth] in -1..1, or null if over the horizon. */
function project(lonDeg, latDeg) {
  const lon = lonDeg * RAD, lat = latDeg * RAD;
  const dl = lon - LON0;
  const cosc = Math.sin(LAT0) * Math.sin(lat) + Math.cos(LAT0) * Math.cos(lat) * Math.cos(dl);
  if (cosc < 0) return null;
  return [
    Math.cos(lat) * Math.sin(dl),
    Math.cos(LAT0) * Math.sin(lat) - Math.sin(LAT0) * Math.cos(lat) * Math.cos(dl),
    cosc,
  ];
}

const land = [];
for (const [cx, cy] of dots) {
  const lon = (cx / 1000) * 360 - 180;
  const lat = 90 - (cy / 500) * 180;
  const p = project(lon, lat);
  /* Drop the last sliver at the limb: at this angle those dots are edge-on,
     they land on top of each other, and they cost bytes to draw a smudge. */
  if (p && p[2] > 0.06) land.push([+p[0].toFixed(4), +p[1].toFixed(4), +p[2].toFixed(3)]);
}

/* The three capitals, projected by the same maths so the beacons sit on the
   land rather than near it. */
const cities = {
  dk: project(12.57, 55.68),
  no: project(10.75, 59.91),
  se: project(18.07, 59.33),
};

writeFileSync(
  "lib/globe-data.ts",
  `/* Generated by scripts/build/globe.mjs from public/world-dots.svg. Do not edit. */\n` +
    `export const LAND: [number, number, number][] = ${JSON.stringify(land)};\n` +
    `export const CITY = ${JSON.stringify(
      Object.fromEntries(
        Object.entries(cities).map(([k, v]) => [k, v && [+v[0].toFixed(4), +v[1].toFixed(4)]]),
      ),
    )} as const;\n`,
);
console.log(`dots in: ${dots.length}  visible: ${land.length}`);
for (const [k, v] of Object.entries(cities)) console.log(k, v ? v.map((n) => n.toFixed(3)).join(" ") : "OVER HORIZON");

/*
 * The graticule.
 *
 * Nothing says "sphere" like the lines of the sphere itself: in orthographic
 * they bow, and the bow is the roundness. Sampled and projected with the same
 * maths as the land, broken wherever a run crosses the horizon so no line
 * takes a shortcut across the disc.
 */
function line(points) {
  const runs = [];
  let cur = [];
  for (const [lon, lat] of points) {
    const p = project(lon, lat);
    if (p && p[2] > 0.02) cur.push(`${p[0].toFixed(4)},${p[1].toFixed(4)}`);
    else if (cur.length > 1) { runs.push(cur); cur = []; }
    else cur = [];
  }
  if (cur.length > 1) runs.push(cur);
  return runs.map((r) => "M" + r.join("L")).join("");
}

const grat = [];
for (let lat = -60; lat <= 60; lat += 30) {
  const pts = [];
  for (let lon = -180; lon <= 180; lon += 3) pts.push([lon, lat]);
  const d = line(pts);
  if (d) grat.push(d);
}
for (let lon = -180; lon < 180; lon += 30) {
  const pts = [];
  for (let lat = -90; lat <= 90; lat += 3) pts.push([lon, lat]);
  const d = line(pts);
  if (d) grat.push(d);
}

writeFileSync(
  "lib/globe-data.ts",
  readFileSync("lib/globe-data.ts", "utf8") +
    `export const GRATICULE: string[] = ${JSON.stringify(grat)};\n`,
);
console.log("graticule paths:", grat.length);
